-- ============================================================================
-- อัปเดตข้อมูล open_days ให้สมจริงตามประเภทสถานที่
-- 
-- หมายเหตุ: ต้องรัน add_open_days.sql ก่อน เพื่อสร้าง column open_days
-- 
-- รูปแบบวันเปิดตามประเภทสถานที่ท่องเที่ยวในประเทศไทย:
--   วัด / ธรรมชาติ       → เปิดทุกวัน
--   พิพิธภัณฑ์ / แหล่งเรียนรู้ → ปิดวันจันทร์ (มาตรฐานพิพิธภัณฑ์ไทย)
--   คาเฟ่              → บางร้านปิดวันอังคาร
--   ร้านอาหาร           → บางร้านปิดวันจันทร์
--   ที่พัก              → เปิดทุกวัน
--   ตลาด / ถนนคนเดิน    → เปิดเฉพาะวันหยุดสุดสัปดาห์
-- ============================================================================

-- ═══════════════════════════════════════════════════════════════════════════════
-- 1. DESTINATIONS (สถานที่ท่องเที่ยว)
-- ═══════════════════════════════════════════════════════════════════════════════

-- 1a. วัด → เปิดทุกวัน
UPDATE destinations
SET open_days = '{mon,tue,wed,thu,fri,sat,sun}'
WHERE category = 'วัด';

-- 1b. ธรรมชาติ → เปิดทุกวัน
UPDATE destinations
SET open_days = '{mon,tue,wed,thu,fri,sat,sun}'
WHERE category = 'ธรรมชาติ';

-- 1c. พิพิธภัณฑ์ / แหล่งเรียนรู้ / อื่นๆ ที่มีลักษณะเป็นแหล่งเรียนรู้ → ปิดวันจันทร์
-- ใช้ ILIKE เพื่อจับชื่อที่มีคำว่า "พิพิธภัณฑ์" หรือ "แหล่งเรียนรู้" หรือ "ศูนย์"
UPDATE destinations
SET open_days = '{tue,wed,thu,fri,sat,sun}'
WHERE name ILIKE '%พิพิธภัณฑ์%'
   OR name ILIKE '%แหล่งเรียนรู้%'
   OR name ILIKE '%ศูนย์%'
   OR name ILIKE '%หอ%';

-- 1d. สวนสนุก / สวนน้ำ → ปิดวันจันทร์-อังคาร (เปิด พุธ-อาทิตย์)
UPDATE destinations
SET open_days = '{wed,thu,fri,sat,sun}'
WHERE name ILIKE '%สวนสนุก%'
   OR name ILIKE '%สวนน้ำ%'
   OR name ILIKE '%water park%';

-- 1e. ตลาด / ถนนคนเดิน → เปิดเฉพาะ ศุกร์-เสาร์-อาทิตย์
UPDATE destinations
SET open_days = '{fri,sat,sun}'
WHERE name ILIKE '%ตลาด%'
   OR name ILIKE '%ถนนคนเดิน%'
   OR name ILIKE '%night market%';

-- ═══════════════════════════════════════════════════════════════════════════════
-- 2. RESTAURANTS (ร้านอาหาร)
-- ═══════════════════════════════════════════════════════════════════════════════

-- 2a. ค่าเริ่มต้น → ส่วนใหญ่เปิดทุกวัน (default ตอน add column แล้ว)
-- ไม่ต้องทำอะไร

-- 2b. คาเฟ่ → บางร้านปิดวันอังคาร (pattern ทั่วไปของคาเฟ่ไทย)
UPDATE restaurants
SET open_days = '{mon,wed,thu,fri,sat,sun}'
WHERE name ILIKE '%คาเฟ่%'
   OR name ILIKE '%cafe%'
   OR name ILIKE '%coffee%'
   OR name ILIKE '%กาแฟ%'
   OR category = 'คาเฟ่';

-- 2c. ร้านอาหารบางร้าน → ปิดวันจันทร์ (ทุก 3 ร้าน ปิด 1 ร้าน เพื่อความหลากหลาย)
-- ใช้ ROW_NUMBER เพื่อเลือกบางร้านให้ปิดวันจันทร์
UPDATE restaurants
SET open_days = '{tue,wed,thu,fri,sat,sun}'
WHERE id IN (
  SELECT id FROM (
    SELECT id, ROW_NUMBER() OVER (ORDER BY id) AS rn
    FROM restaurants
    WHERE category IS DISTINCT FROM 'คาเฟ่'
      AND name NOT ILIKE '%คาเฟ่%'
      AND name NOT ILIKE '%cafe%'
      AND name NOT ILIKE '%coffee%'
  ) sub
  WHERE rn % 3 = 0  -- ทุก 3 ร้าน ปิด 1 ร้าน
);

